#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Annotate real bulk PanTCR allele calls with evidence-supported vs completed sites.

This script does not change genotype calls. It reads the public-bulk summary
tables, PanTCR inference CSVs, mutation evidence tables, and graph priors
generated by the public-bulk application pipeline. For each unmatched TRBV
summary allele, it reports which non-reference sites in the called sequence are
directly supported by filtered mutation evidence and which are completed only by
the graph/reference prior under the same dynamic-programming completion logic
used in code/pantcr/infer_genotype_bayes.py.
"""

from __future__ import annotations

import argparse
import importlib.util
import math
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Set, Tuple

import pandas as pd

PACKAGE_ROOT = Path(__file__).resolve().parents[3]
EXPERIMENT_DIR = PACKAGE_ROOT / "experiments" / Path(__file__).resolve().parent.name


SIDE_LABELS = ("A", "B", "C", "D")
DATABASE_HIT_TERMS = ("IMGT", "pmTR", "VDJ.online", "VDJ")
MANUSCRIPT_KNOWN_TERMS = ("IMGT", "pmTR")
MANUSCRIPT_HIGHLIGHTED_VDJ_PREFIX = (
    "AATGCTGGTGTCACTCAGACCCCAAAATTCCAGGTCCTGAAGACAGGACAGAGCATGACACTGCAGTGTGCCCAGGATAT"
    "GAACCATGAATACATGTCCTGGTATCGACAAGACCCAGGCATGGGGCTGAGGCTGATTCATTACTCAGTTGGTGCTGGTA"
    "TCACTGACCAAGGAGAAGTCCCCAATGGCTACAATGTCTCCAGATCAACCACAGAGGATTTCCCGCTCAGGCTGCTGTCA"
    "GCTGCTCCCTCCCAGACATCTGTGTACTTC"
)


@dataclass(frozen=True)
class DatasetConfig:
    label: str
    root: Path
    summary: Path
    note_col: Optional[str]


def load_infer_module(script_path: Path, module_name: str):
    spec = importlib.util.spec_from_file_location(module_name, script_path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Cannot import inference script: {script_path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    spec.loader.exec_module(module)
    return module


def infer_module_path(dataset_root: Path) -> Path:
    package_candidate = PACKAGE_ROOT / "code" / "pantcr" / "infer_genotype_bayes.py"
    if package_candidate.exists():
        return package_candidate
    raise FileNotFoundError(
        f"Could not find package inference module: {package_candidate}."
    )


def clean_seq(x: object) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return ""
    return str(x).strip().upper().replace(" ", "")


def split_filenames(x: object) -> List[str]:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return []
    return [p.strip() for p in str(x).split("|") if p.strip()]


def contains_any(text: str, terms: Iterable[str]) -> bool:
    upper = text.upper()
    return any(term.upper() in upper for term in terms)


def classify_summary_row(match_status: str, note: str) -> Tuple[str, str, str]:
    """Return (fig4 class, broad source class, database-hit subtype)."""
    if str(match_status) == "Matched":
        return "IMGT_or_known", "matched_reference", "matched_reference"
    if contains_any(note, MANUSCRIPT_KNOWN_TERMS):
        has_imgt = contains_any(note, ["IMGT"])
        has_pmtr = contains_any(note, ["pmTR"])
        if has_imgt and has_pmtr:
            hit = "IMGT_and_pmTR"
        elif has_imgt:
            hit = "IMGT"
        else:
            hit = "pmTR"
        return "IMGT_or_known", "external_database_hit", hit
    if contains_any(note, DATABASE_HIT_TERMS):
        return "novel_candidate", "external_database_hit", "VDJ.online_or_VDJ"
    return "novel_candidate", "not_database_matched", "no_database_hit"


def seq_matches_summary(infer_seq: str, summary_seq: str) -> bool:
    """Summary sequences are no-CDR3 mature-region prefixes of infer seqs."""
    infer_seq = clean_seq(infer_seq)
    summary_seq = clean_seq(summary_seq)
    if not infer_seq or not summary_seq:
        return False
    return infer_seq == summary_seq or infer_seq.startswith(summary_seq)


def summary_match_mode(infer_seq: str, summary_seq: str) -> str:
    infer_seq = clean_seq(infer_seq)
    summary_seq = clean_seq(summary_seq)
    if not infer_seq or not summary_seq:
        return "no_match"
    if infer_seq == summary_seq:
        return "exact_sequence_match"
    if infer_seq.startswith(summary_seq):
        return "mature_prefix_match"
    return "no_match"


def token_for_side(v3_exact: object, side: str) -> str:
    if v3_exact is None or (isinstance(v3_exact, float) and math.isnan(v3_exact)):
        return ""
    parts = [p.strip() for p in str(v3_exact).split("|")]
    idx = SIDE_LABELS.index(side)
    if idx < len(parts):
        return parts[idx]
    if len(parts) == 1:
        return parts[0]
    return ""


def in_any_range(pos0: int, ranges: List[Tuple[int, int]]) -> bool:
    return any(int(a) <= pos0 < int(b) for a, b in ranges)


def compact_pos_ranges_1based(positions: Iterable[int]) -> str:
    vals = sorted(set(int(p) for p in positions))
    if not vals:
        return ""
    ranges = []
    start = prev = vals[0]
    for pos in vals[1:]:
        if pos == prev + 1:
            prev = pos
            continue
        ranges.append((start, prev))
        start = prev = pos
    ranges.append((start, prev))
    out = []
    for a, b in ranges:
        if a == b:
            out.append(str(a + 1))
        else:
            out.append(f"{a + 1}-{b + 1}")
    return ";".join(out)


def mature_position_support_summary(evidences, ref: str, filled_amap: Dict[int, str], mature_limit: int) -> dict:
    mature_positions = set(range(max(0, mature_limit)))
    covered_positions: Set[int] = set()
    supported_positions: Set[int] = set()
    conflict_positions: Set[int] = set()

    for ev in evidences:
        for a, b in ev.ranges:
            a2 = max(0, int(a))
            b2 = min(mature_limit, int(b), len(ref))
            for pos0 in range(a2, b2):
                covered_positions.add(pos0)
                called_state = filled_amap.get(pos0, ref[pos0].upper())
                obs_state = ev.state_map.get(pos0, ref[pos0].upper())
                if obs_state == called_state:
                    supported_positions.add(pos0)
                else:
                    conflict_positions.add(pos0)

    imputed_positions = mature_positions - covered_positions
    covered_without_matching = covered_positions - supported_positions
    return {
        "mature_evidence_covered_position_count": len(covered_positions),
        "mature_graph_imputed_position_count": len(imputed_positions),
        "mature_uncovered_graph_or_reference_completed_position_count": len(imputed_positions),
        "mature_supported_position_count": len(supported_positions),
        "mature_conflict_position_count": len(conflict_positions),
        "mature_covered_without_matching_evidence_count": len(covered_without_matching),
        "mature_evidence_covered_ranges_1based": compact_pos_ranges_1based(covered_positions),
        "mature_graph_imputed_ranges_1based": compact_pos_ranges_1based(imputed_positions),
        "mature_uncovered_graph_or_reference_completed_ranges_1based": compact_pos_ranges_1based(imputed_positions),
        "mature_conflict_positions_1based": compact_pos_ranges_1based(conflict_positions),
    }


def site_label(pos0: int, ref_state: str, target_state: str) -> str:
    return f"{pos0 + 1}:{ref_state}>{target_state}"


def get_ref_and_priors(root: Path, infer_mod, fam: str, cache: Dict[Tuple[Path, str], dict],
                       sample_df: Optional[pd.DataFrame] = None) -> dict:
    key = (root, fam)
    if key in cache:
        return cache[key]

    pang_dir = root / "pang" / "semi" / "V"
    node_df = pd.read_csv(pang_dir / "node_support_long.csv")
    edge_path = pang_dir / "edge_support_long.csv"
    edge_df = pd.read_csv(edge_path) if edge_path.exists() else None
    gfa = pang_dir / "graphs" / f"{fam}.gfa"
    has_gfa_ref = gfa.exists()
    ref = infer_mod.parse_gfa_ref(gfa, fam) if has_gfa_ref else ""
    if not ref and sample_df is not None:
        ref = infer_mod.fallback_ref_from_sample(sample_df)
    if not ref:
        raise FileNotFoundError(f"No graph reference for {fam}: {gfa}")

    nodep = infer_mod.NodePriors(fam, node_df, None, alpha=1e-6)
    edgep = infer_mod.EdgePriors(fam, edge_df, None, alpha=1e-6) if edge_df is not None else None
    info = {"ref": ref, "nodep": nodep, "edgep": edgep, "ref_source": "gfa" if has_gfa_ref else "sample_fallback"}
    if has_gfa_ref:
        cache[key] = info
    return info


def support_for_site(infer_mod, evidences, ref: str, pos0: int, target_state: str) -> dict:
    ref_state = ref[pos0].upper()
    covered_count = 0
    support_count = 0
    conflict_count = 0
    support_weight = 0.0
    conflict_weight = 0.0
    support_mut_infos: Set[str] = set()
    conflict_mut_infos: Set[str] = set()

    for ev in evidences:
        if not in_any_range(pos0, ev.ranges):
            continue
        covered_count += 1
        obs_state = ev.state_map.get(pos0, ref_state)
        if obs_state == target_state:
            support_count += 1
            support_weight += float(ev.weight)
            support_mut_infos.add(str(ev.mut_info))
        else:
            conflict_count += 1
            conflict_weight += float(ev.weight)
            conflict_mut_infos.add(str(ev.mut_info))

    if support_count > 0 and conflict_count == 0:
        cls = "unconflicted_read_supported"
    elif support_count > 0:
        cls = "read_supported_with_conflict"
    elif covered_count == 0:
        cls = "graph_imputed"
    else:
        cls = "covered_but_not_supported"

    return {
        "site_class": cls,
        "site_class_broad": "read_supported" if support_count > 0 else cls,
        "covered_evidence_count": covered_count,
        "support_evidence_count": support_count,
        "conflict_evidence_count": conflict_count,
        "support_weight": round(support_weight, 6),
        "conflict_weight": round(conflict_weight, 6),
        "support_mut_infos": "|".join(sorted(support_mut_infos)),
        "conflict_mut_infos": "|".join(sorted(conflict_mut_infos)),
    }


def summarize_sites(site_rows: List[dict]) -> dict:
    if not site_rows:
        return {
            "variant_site_count": 0,
            "read_supported_site_count": 0,
            "unconflicted_read_supported_site_count": 0,
            "read_supported_with_conflict_site_count": 0,
            "graph_imputed_site_count": 0,
            "covered_but_not_supported_site_count": 0,
            "read_supported_sites": "",
            "unconflicted_read_supported_sites": "",
            "read_supported_with_conflict_sites": "",
            "graph_imputed_sites": "",
            "covered_but_not_supported_sites": "",
        }
    by_site: Dict[str, Set[str]] = {}
    for row in site_rows:
        by_site.setdefault(row["site"], set()).add(row["site_class"])

    def sites_with(cls: str) -> List[str]:
        return sorted(site for site, classes in by_site.items() if cls in classes)

    unconflicted = sites_with("unconflicted_read_supported")
    with_conflict = sites_with("read_supported_with_conflict")
    read_supported = sorted(set(unconflicted) | set(with_conflict))
    graph_imputed = [site for site in sites_with("graph_imputed") if site not in read_supported]
    uncovered_or_conflict = [
        site for site in sites_with("covered_but_not_supported")
        if site not in read_supported and site not in graph_imputed
    ]
    return {
        "variant_site_count": len(by_site),
        "read_supported_site_count": len(read_supported),
        "unconflicted_read_supported_site_count": len(unconflicted),
        "read_supported_with_conflict_site_count": len(with_conflict),
        "graph_imputed_site_count": len(graph_imputed),
        "covered_but_not_supported_site_count": len(uncovered_or_conflict),
        "read_supported_sites": ";".join(read_supported),
        "unconflicted_read_supported_sites": ";".join(unconflicted),
        "read_supported_with_conflict_sites": ";".join(with_conflict),
        "graph_imputed_sites": ";".join(graph_imputed),
        "covered_but_not_supported_sites": ";".join(uncovered_or_conflict),
    }


def classify_mature_position(support: dict, is_variant: bool) -> str:
    if is_variant:
        return str(support["site_class"])
    covered = int(support["covered_evidence_count"])
    supported = int(support["support_evidence_count"])
    conflicts = int(support["conflict_evidence_count"])
    if covered == 0:
        return "reference_state_graph_or_reference_completed_uncovered"
    if supported > 0 and conflicts == 0:
        return "reference_state_unconflicted_read_supported"
    if supported > 0 and conflicts > 0:
        return "reference_state_read_supported_with_conflict"
    return "reference_state_covered_but_not_supported"


def mature_position_support_for_output(support: dict, is_variant: bool) -> dict:
    out = dict(support)
    if is_variant:
        return out
    cls = classify_mature_position(support, is_variant=False)
    out["site_class"] = cls
    out["site_class_broad"] = cls
    return out


def annotate_dataset(
    config: DatasetConfig,
    min_naive: int,
    include_mature_position_detail: bool = False,
) -> Tuple[List[dict], List[dict], List[dict], List[dict], List[dict]]:
    root = config.root
    infer_mod = load_infer_module(infer_module_path(root), f"infer_mod_{config.label.replace('-', '_')}")
    summary_df = pd.read_csv(config.summary)
    note_col = config.note_col or ("note" if "note" in summary_df.columns else summary_df.columns[-1])

    candidates = summary_df[
        summary_df["family"].astype(str).str.startswith("TRBV")
        & (summary_df["match_status"].astype(str) == "Unmatched")
    ].copy()

    infer_dir = root / "infer" / "PanTCR" / "V"
    mutation_dir = root / "mutations" / "V"

    ref_cache: Dict[Tuple[Path, str], dict] = {}
    mutation_cache: Dict[str, pd.DataFrame] = {}
    infer_cache: Dict[str, pd.DataFrame] = {}
    evidence_cache: Dict[Tuple[str, str], tuple] = {}

    call_rows: List[dict] = []
    site_rows: List[dict] = []
    position_rows: List[dict] = []
    summary_rows: List[dict] = []
    check_rows: List[dict] = []

    for summary_idx, row in candidates.reset_index(drop=True).iterrows():
        fam = str(row["family"])
        target_seq = clean_seq(row["sequence"])
        note = "" if pd.isna(row[note_col]) else str(row[note_col])
        fig4_class, evidence_class, database_hit_type = classify_summary_row(row["match_status"], note)
        filenames = split_filenames(row["filenames"])
        expected_count = int(row["sample_counts"]) if not pd.isna(row["sample_counts"]) else len(filenames)
        is_highlighted_vdj = (
            config.label == "BULK-1"
            and fam == "TRBV6-5"
            and "VDJ.ONLINE" in note.upper()
            and target_seq == MANUSCRIPT_HIGHLIGHTED_VDJ_PREFIX
        )

        row_key = f"{config.label}:{fam}:{summary_idx + 1}"
        matched_samples: Set[str] = set()
        row_site_rows: List[dict] = []
        row_call_rows: List[dict] = []
        missing_files: List[str] = []
        unmatched_files: List[str] = []
        ambiguous_files: List[str] = []
        multi_side_files: List[str] = []
        same_sequence_multi_side_files: List[str] = []

        for infer_name in filenames:
            infer_path = infer_dir / infer_name
            if not infer_path.exists():
                missing_files.append(infer_name)
                continue

            if infer_name not in infer_cache:
                infer_cache[infer_name] = pd.read_csv(infer_path)
            infer_df = infer_cache[infer_name]
            fam_df = infer_df[infer_df["gene"].astype(str) == fam]
            if fam_df.empty:
                unmatched_files.append(infer_name)
                continue

            candidate_matches = []
            for row_idx, candidate_row in fam_df.iterrows():
                matching_sides = []
                for side in SIDE_LABELS:
                    seq_col = f"seq_{side}"
                    if seq_col in candidate_row.index and seq_matches_summary(candidate_row[seq_col], target_seq):
                        matching_sides.append(side)
                if matching_sides:
                    candidate_matches.append((row_idx, candidate_row, matching_sides))
            if not candidate_matches:
                unmatched_files.append(infer_name)
                continue
            if len(candidate_matches) > 1:
                ambiguous_files.append(infer_name)
                continue
            _row_idx, infer_row, matching_sides = candidate_matches[0]

            sample_id = infer_name.replace("infer_", "").replace(".V.csv", "")
            mutation_path = mutation_dir / f"{sample_id}.V_sequences.csv"
            if sample_id not in mutation_cache:
                mutation_cache[sample_id] = pd.read_csv(mutation_path)
            sample_df = mutation_cache[sample_id]
            sdf = sample_df[sample_df["Family"].astype(str) == fam].copy()

            ref_info = get_ref_and_priors(root, infer_mod, fam, ref_cache, sample_df=sdf)
            ref = ref_info["ref"]
            evidence_key = (sample_id, fam)
            if evidence_key not in evidence_cache:
                evidence_cache[evidence_key] = infer_mod.build_evidence_items(sdf, ref, min_naive=min_naive)
            evidences, mut_infos, covered = evidence_cache[evidence_key]

            # A homozygous K=1 call is duplicated into A/B in the inference CSV;
            # count the sample once for the summary allele.
            chosen_sides = matching_sides
            if len(matching_sides) > 1:
                seqs = {clean_seq(infer_row.get(f"seq_{s}", "")) for s in matching_sides}
                if len(seqs) == 1:
                    same_sequence_multi_side_files.append(infer_name)
                    chosen_sides = [matching_sides[0]]
                else:
                    multi_side_files.append(infer_name)

            complete_amap = getattr(infer_mod, "graph_guided_complete_amap", None)
            if complete_amap is None:
                complete_amap = getattr(infer_mod, "v" + "iterbi_fill_amap")

            for side in chosen_sides:
                mut_str = token_for_side(infer_row.get("v3_alleles_exact", ""), side)
                base_amap = infer_mod.allele_map_from_tokens(ref, infer_mod.parse_mutation_info(mut_str))
                filled_amap = complete_amap(ref, base_amap, covered, ref_info["nodep"], ref_info["edgep"])
                computed_seq = infer_mod.amap_to_sequence(ref, filled_amap)
                infer_seq = clean_seq(infer_row.get(f"seq_{side}", ""))
                mature_ref_limit = min(len(ref), len(target_seq))
                mature_support = mature_position_support_summary(evidences, ref, filled_amap, mature_ref_limit)

                this_site_rows: List[dict] = []
                this_position_rows: List[dict] = []
                variant_positions = [
                    pos0 for pos0, state in sorted(filled_amap.items())
                    if pos0 < mature_ref_limit and state != ref[pos0].upper()
                ]
                variant_position_set = set(variant_positions)

                position_context = {
                    "dataset": config.label,
                    "row_key": row_key,
                    "family": fam,
                    "sample_id": sample_id,
                    "infer_file": infer_name,
                    "allele_side": side,
                    "note": note,
                    "is_manuscript_highlighted_vdj_online": is_highlighted_vdj,
                    "manuscript_fig4_class": fig4_class,
                    "evidence_source_class": evidence_class,
                    "database_hit_type": database_hit_type,
                }
                if include_mature_position_detail:
                    for pos0 in range(mature_ref_limit):
                        ref_state = ref[pos0].upper()
                        called_state = filled_amap.get(pos0, ref_state)
                        target_state = target_seq[pos0].upper() if pos0 < len(target_seq) else ""
                        is_variant = pos0 in variant_position_set
                        support = support_for_site(infer_mod, evidences, ref, pos0, called_state)
                        output_support = mature_position_support_for_output(support, is_variant)
                        this_position_rows.append({
                            **position_context,
                            "pos0": pos0,
                            "pos1": pos0 + 1,
                            "ref_state": ref_state,
                            "called_state": called_state,
                            "summary_target_state": target_state,
                            "is_nonreference_variant": is_variant,
                            "called_matches_summary_state": called_state == target_state,
                            "position_class": classify_mature_position(support, is_variant),
                            **output_support,
                        })

                for pos0 in variant_positions:
                    ref_state = ref[pos0].upper()
                    target_state = filled_amap[pos0]
                    support = support_for_site(infer_mod, evidences, ref, pos0, target_state)
                    token_site = pos0 in base_amap
                    site = site_label(pos0, ref_state, target_state)
                    site_row = {
                        "dataset": config.label,
                        "row_key": row_key,
                        "family": fam,
                        "sample_id": sample_id,
                        "infer_file": infer_name,
                        "allele_side": side,
                        "note": note,
                        "is_manuscript_highlighted_vdj_online": is_highlighted_vdj,
                        "manuscript_fig4_class": fig4_class,
                        "evidence_source_class": evidence_class,
                        "database_hit_type": database_hit_type,
                        "pos0": pos0,
                        "pos1": pos0 + 1,
                        "ref_state": ref_state,
                        "called_state": target_state,
                        "site": site,
                        "in_raw_candidate_token": token_site,
                        **support,
                    }
                    this_site_rows.append(site_row)

                site_summary = summarize_sites(this_site_rows)
                call_row = {
                    "dataset": config.label,
                    "row_key": row_key,
                    "family": fam,
                    "sample_id": sample_id,
                    "infer_file": infer_name,
                    "allele_side": side,
                    "summary_sample_counts": expected_count,
                    "match_status": row["match_status"],
                    "note": note,
                    "is_manuscript_highlighted_vdj_online": is_highlighted_vdj,
                    "manuscript_fig4_class": fig4_class,
                    "evidence_source_class": evidence_class,
                    "database_hit_type": database_hit_type,
                    "v3_K": infer_row.get("v3_K", ""),
                    "v3_note": infer_row.get("v3_note", ""),
                    "v3_pi": infer_row.get("v3_pi", ""),
                    "v3_alleles_exact_all": infer_row.get("v3_alleles_exact", ""),
                    "allele_mutation_token": mut_str,
                    "infer_seq_matches_summary_prefix": seq_matches_summary(infer_seq, target_seq),
                    "summary_sequence_match_mode": summary_match_mode(infer_seq, target_seq),
                    "summary_prefix_length": len(target_seq),
                    "computed_seq_matches_infer_side": clean_seq(computed_seq) == infer_seq,
                    "computed_seq_matches_summary_prefix": seq_matches_summary(computed_seq, target_seq),
                    "computed_summary_sequence_match_mode": summary_match_mode(computed_seq, target_seq),
                    "mature_region_length_from_summary": len(target_seq),
                    "graph_ref_length": len(ref),
                    "site_classified_length": mature_ref_limit,
                    "unclassified_tail_length_difference": abs(len(target_seq) - len(ref)),
                    "target_tail_beyond_graph_ref": target_seq[len(ref):] if len(target_seq) > len(ref) else "",
                    "graph_ref_tail_beyond_target": ref[len(target_seq):] if len(ref) > len(target_seq) else "",
                    "ref_source": ref_info["ref_source"],
                    "filtered_evidence_items": len(evidences),
                    "filtered_covered_positions": len(covered),
                    **mature_support,
                    **site_summary,
                }
                row_call_rows.append(call_row)
                row_site_rows.extend(this_site_rows)
                position_rows.extend(this_position_rows)
                matched_samples.add(sample_id)

        row_site_summary = summarize_sites(row_site_rows)
        call_frame = pd.DataFrame(row_call_rows)
        if call_frame.empty:
            match_modes = {}
            computed_seq_matches_infer_side_all = False
            computed_seq_matches_summary_prefix_all = False
            computed_seq_mismatch_infer_side_n = 0
            computed_seq_mismatch_summary_prefix_n = 0
        else:
            match_modes = call_frame["summary_sequence_match_mode"].astype(str).value_counts().to_dict()
            computed_seq_matches_infer_side_all = bool(call_frame["computed_seq_matches_infer_side"].astype(bool).all())
            computed_seq_matches_summary_prefix_all = bool(call_frame["computed_seq_matches_summary_prefix"].astype(bool).all())
            computed_seq_mismatch_infer_side_n = int((~call_frame["computed_seq_matches_infer_side"].astype(bool)).sum())
            computed_seq_mismatch_summary_prefix_n = int((~call_frame["computed_seq_matches_summary_prefix"].astype(bool)).sum())
        summary_row = {
            "dataset": config.label,
            "row_key": row_key,
            "family": fam,
            "sequence": target_seq,
            "sample_counts": expected_count,
            "matched_unique_samples": len(matched_samples),
            "matched_call_rows": len(row_call_rows),
            "match_status": row["match_status"],
            "note": note,
            "is_manuscript_highlighted_vdj_online": is_highlighted_vdj,
            "manuscript_fig4_class": fig4_class,
            "evidence_source_class": evidence_class,
            "database_hit_type": database_hit_type,
            "missing_infer_files": "|".join(missing_files),
            "infer_files_without_matching_sequence": "|".join(unmatched_files),
            "ambiguous_matching_infer_files": "|".join(ambiguous_files),
            "multi_side_matching_infer_files": "|".join(multi_side_files),
            "same_sequence_multi_side_matching_infer_files": "|".join(same_sequence_multi_side_files),
            "sample_count_matches_summary": len(matched_samples) == expected_count,
            "summary_exact_match_call_n": int(match_modes.get("exact_sequence_match", 0)),
            "summary_mature_prefix_match_call_n": int(match_modes.get("mature_prefix_match", 0)),
            "summary_no_match_call_n": int(match_modes.get("no_match", 0)),
            "computed_seq_matches_infer_side_all": computed_seq_matches_infer_side_all,
            "computed_seq_matches_summary_prefix_all": computed_seq_matches_summary_prefix_all,
            "computed_seq_mismatch_infer_side_n": computed_seq_mismatch_infer_side_n,
            "computed_seq_mismatch_summary_prefix_n": computed_seq_mismatch_summary_prefix_n,
            "max_unclassified_tail_length_difference": max(
                [int(r.get("unclassified_tail_length_difference", 0)) for r in row_call_rows] or [0]
            ),
            **row_site_summary,
        }
        summary_rows.append(summary_row)
        call_rows.extend(row_call_rows)
        site_rows.extend(row_site_rows)
        check_rows.append({
            "dataset": config.label,
            "row_key": row_key,
            "family": fam,
            "expected_sample_count": expected_count,
            "matched_unique_samples": len(matched_samples),
            "matched_call_rows": len(row_call_rows),
            "sample_count_matches_summary": len(matched_samples) == expected_count,
            "missing_infer_files_n": len(missing_files),
            "unmatched_infer_files_n": len(unmatched_files),
            "ambiguous_infer_files_n": len(ambiguous_files),
            "multi_side_matching_infer_files_n": len(multi_side_files),
            "same_sequence_multi_side_matching_infer_files_n": len(same_sequence_multi_side_files),
            "computed_seq_matches_infer_side_all": computed_seq_matches_infer_side_all,
            "computed_seq_matches_summary_prefix_all": computed_seq_matches_summary_prefix_all,
            "computed_seq_mismatch_infer_side_n": computed_seq_mismatch_infer_side_n,
            "computed_seq_mismatch_summary_prefix_n": computed_seq_mismatch_summary_prefix_n,
            "summary_exact_match_call_n": int(match_modes.get("exact_sequence_match", 0)),
            "summary_mature_prefix_match_call_n": int(match_modes.get("mature_prefix_match", 0)),
            "summary_no_match_call_n": int(match_modes.get("no_match", 0)),
            "missing_infer_files": "|".join(missing_files),
            "unmatched_infer_files": "|".join(unmatched_files),
            "ambiguous_infer_files": "|".join(ambiguous_files),
            "multi_side_matching_infer_files": "|".join(multi_side_files),
            "same_sequence_multi_side_matching_infer_files": "|".join(same_sequence_multi_side_files),
        })

    return summary_rows, call_rows, site_rows, position_rows, check_rows


def make_classification_counts(summary_rows: List[dict]) -> pd.DataFrame:
    df = pd.DataFrame(summary_rows)
    if df.empty:
        return pd.DataFrame()
    records = []
    for dataset, sub in df.groupby("dataset"):
        records.append({
            "dataset": dataset,
            "unmatched_TRBV_rows": len(sub),
            "manuscript_novel_candidate_rows": int((sub["manuscript_fig4_class"] == "novel_candidate").sum()),
            "external_database_hit_rows": int((sub["evidence_source_class"] == "external_database_hit").sum()),
            "vdj_online_or_vdj_hit_novel_candidate_rows": int(
                ((sub["manuscript_fig4_class"] == "novel_candidate")
                 & (sub["database_hit_type"] == "VDJ.online_or_VDJ")).sum()
            ),
            "not_database_matched_rows": int((sub["evidence_source_class"] == "not_database_matched").sum()),
            "rows_with_any_read_supported_variant": int((sub["read_supported_site_count"] > 0).sum()),
            "rows_with_any_unconflicted_read_supported_variant": int(
                (sub["unconflicted_read_supported_site_count"] > 0).sum()
            ),
            "rows_with_any_read_supported_variant_with_conflict": int(
                (sub["read_supported_with_conflict_site_count"] > 0).sum()
            ),
            "rows_with_only_graph_imputed_variant_sites": int(
                ((sub["variant_site_count"] > 0) & (sub["read_supported_site_count"] == 0)).sum()
            ),
            "rows_without_nonreference_variant_sites": int((sub["variant_site_count"] == 0).sum()),
        })
    return pd.DataFrame(records)


def main() -> None:
    ap = argparse.ArgumentParser()
    benchmark_root = (
        PACKAGE_ROOT
        / "experiments"
        / "01_in_silico_trbv_benchmarks"
        / "benchmark_pipelines"
        / "04_public_bulk_rnaseq"
        / "generated"
    )
    ap.add_argument("--bulk1-root", default=str(benchmark_root / "BULK-1"))
    ap.add_argument("--bulk2-root", default=str(benchmark_root / "BULK-2"))
    ap.add_argument("--outdir", default=str(EXPERIMENT_DIR / "generated" / "evidence_imputation"))
    ap.add_argument("--min-naive", type=int, default=2)
    ap.add_argument(
        "--write-mature-position-detail",
        action="store_true",
        help="Write the large per-mature-position detail CSV. Off by default for the lightweight GitHub package.",
    )
    args = ap.parse_args()

    configs = [
        DatasetConfig(
            label="BULK-1",
            root=Path(args.bulk1_root),
            summary=Path(args.bulk1_root) / "candidate_allele_summary.csv",
            note_col="note",
        ),
        DatasetConfig(
            label="BULK-2",
            root=Path(args.bulk2_root),
            summary=Path(args.bulk2_root) / "candidate_allele_summary.csv",
            note_col=None,
        ),
    ]

    outdir = Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)

    all_summary: List[dict] = []
    all_calls: List[dict] = []
    all_sites: List[dict] = []
    all_positions: List[dict] = []
    all_checks: List[dict] = []
    for config in configs:
        summary_rows, call_rows, site_rows, position_rows, check_rows = annotate_dataset(
            config,
            min_naive=args.min_naive,
            include_mature_position_detail=args.write_mature_position_detail,
        )
        all_summary.extend(summary_rows)
        all_calls.extend(call_rows)
        all_sites.extend(site_rows)
        all_positions.extend(position_rows)
        all_checks.extend(check_rows)

    summary_df = pd.DataFrame(all_summary)
    calls_df = pd.DataFrame(all_calls)
    sites_df = pd.DataFrame(all_sites)
    positions_df = pd.DataFrame(all_positions)
    checks_df = pd.DataFrame(all_checks)
    counts_df = make_classification_counts(all_summary)

    summary_df.to_csv(outdir / "bulk_candidate_support_summary.csv", index=False, encoding="utf-8-sig")
    calls_df.to_csv(outdir / "bulk_candidate_call_support.csv", index=False, encoding="utf-8-sig")
    sites_df.to_csv(outdir / "bulk_candidate_site_detail.csv", index=False, encoding="utf-8-sig")
    mature_detail_path = outdir / "bulk_candidate_mature_position_detail.csv"
    if args.write_mature_position_detail:
        positions_df.to_csv(mature_detail_path, index=False, encoding="utf-8-sig")
    elif mature_detail_path.exists():
        mature_detail_path.unlink()
    checks_df.to_csv(outdir / "bulk_candidate_consistency_checks.csv", index=False, encoding="utf-8-sig")
    counts_df.to_csv(outdir / "bulk_candidate_classification_counts.csv", index=False, encoding="utf-8-sig")

    if not checks_df.empty:
        failure_mask = ~checks_df["sample_count_matches_summary"].astype(bool)
        for col in [
            "missing_infer_files_n",
            "unmatched_infer_files_n",
            "ambiguous_infer_files_n",
            "computed_seq_mismatch_infer_side_n",
            "computed_seq_mismatch_summary_prefix_n",
            "summary_no_match_call_n",
        ]:
            if col in checks_df.columns:
                failure_mask = failure_mask | (pd.to_numeric(checks_df[col], errors="coerce").fillna(0) > 0)
        failed = checks_df[failure_mask]
    else:
        failed = checks_df
    print(f"Wrote results to {outdir}")
    print(f"Summary rows: {len(summary_df)}; call rows: {len(calls_df)}; site rows: {len(sites_df)}; position rows: {len(positions_df)}")
    print(f"Consistency failures: {0 if failed is None else len(failed)}")
    if failed is not None and len(failed) > 0:
        print(failed[["dataset", "family", "expected_sample_count", "matched_unique_samples", "missing_infer_files_n", "unmatched_infer_files_n"]].to_string(index=False))
        raise RuntimeError("Bulk evidence/imputation consistency checks failed")


if __name__ == "__main__":
    main()
